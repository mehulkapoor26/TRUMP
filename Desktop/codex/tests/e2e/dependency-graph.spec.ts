import { test, expect } from '@playwright/test';
import { ZipFile } from 'yazl';
import { readFile } from 'node:fs/promises';
import { once } from 'node:events';
import type { ScanResult, VulnerabilityReport } from '../../shared/src/index.js';

test('real upload renders edges, selects versioned nodes, and separates advisory matches from exploitability', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const zip = new ZipFile(); const chunks: Buffer[] = [];
  zip.outputStream.on('data', chunk => chunks.push(chunk)); const end = once(zip.outputStream, 'end');
  for (const file of ['package.json', 'package-lock.json', 'src/entry.js']) zip.addBuffer(await readFile(`tests/fixtures/npm-project/${file}`), file);
  zip.end(); await end;
  await page.goto('/#/scanner');
  let graphData: ScanResult['graph'];
  await page.route('**/api/scans/*/vulnerabilities', async route => {
    while (!graphData) await new Promise(resolve => setTimeout(resolve, 10));
    const graph = graphData;
    const selected = graph.nodes.find(n => n.name === 'is-number' && n.version === '6.0.0')!;
    const report: VulnerabilityReport = { source: 'OSV', checkedAt: new Date().toISOString(), status: 'complete', warnings: [], checks: graph.nodes.map(n => ({ nodeId: n.id, status: n.id === selected.id ? 'matched' : n.isProject ? 'unknown' : 'no-known', complete: !n.isProject, advisoryIds: n.id === selected.id ? ['GHSA-test-fixture'] : [] })) };
    return route.fulfill({ json: report });
  });
  await page.getByRole('combobox', { name: 'Project source' }).selectOption('zip');
  await page.getByLabel(/ZIP file \(up to .* MiB\)/).setInputFiles({ name: 'fixture.zip', mimeType: 'application/zip', buffer: Buffer.concat(chunks) });
  const scanned = page.waitForResponse(r => r.url().endsWith('/api/scans') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Scan My Project', exact: true }).click();
  const scan = await (await scanned).json() as ScanResult;
  const graph = scan.graph!; graphData = graph;
  await expect(page.getByRole('heading', { name: 'Project scan results', exact: true })).toBeVisible();
  await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'Dependency map' }).click();
  const selected = graph.nodes.find(n => n.name === 'is-number' && n.version === '6.0.0')!;
  const otherVersion = graph.nodes.find(n => n.name === 'is-number' && n.version === '7.0.0')!;
  await expect(page.locator('.react-flow__node')).toHaveCount(graph.nodes.length);
  await expect(page.locator('.react-flow__edge')).toHaveCount(graph.edges.length);
  await page.locator(`[data-id="${selected.id}"]`).click();
  const details = page.getByRole('complementary', { name: 'Selected package details' });
  await expect(details.getByRole('heading', { name: 'is-number@6.0.0', exact: true })).toBeVisible();
  await expect(details).toContainText('traceguard-sbom-fixture@1.0.0 → is-odd@3.0.1 → is-number@6.0.0');
  await expect(details).toContainText('Immediate parents (1)');
  await expect(page.getByRole('heading', { name: 'Actual exploitability: not assessed' })).toBeVisible();
  // The UI calls the production endpoint; this fixture keeps the advisory response deterministic.
  await page.getByRole('button', { name: 'Check security findings' }).click();
  await expect(details.getByRole('link', { name: 'GHSA-test-fixture' })).toBeVisible();
  await expect(page.locator(`[data-id="${selected.id}"]`)).toHaveCSS('border-top-color', 'rgb(196, 181, 253)');
  await expect(page.locator(`[data-id="${selected.id}"]`)).toHaveCSS('background-color', 'rgb(69, 26, 36)');
  await expect(page.getByRole('heading', { name: 'Actual exploitability: not assessed' })).toBeVisible();
  await page.getByLabel('Find a package instance').fill('7.0.0');
  await page.getByRole('button', { name: /is-number@7.0.0/ }).click();
  await expect(details).toContainText('This is not a safety guarantee.');
  await expect(page.locator(`[data-id="${otherVersion.id}"]`)).toContainText('No known match');
  const reachability = page.getByRole('region', { name: 'Scoped function reachability' });
  await reachability.getByLabel('Affected export (user-declared)', { exact: true }).fill('default');
  await reachability.getByRole('button', { name: 'Analyze scoped reachability' }).click();
  await expect(reachability.getByRole('status')).toContainText('NOT REACHABLE — within declared analysis coverage only');
  await reachability.getByLabel('Entry export or <module>').fill('handler');
  await reachability.getByRole('button', { name: 'Analyze scoped reachability' }).click();
  await expect(reachability.getByRole('status')).toContainText('REACHABLE — static exported-boundary call path');
  await expect(reachability).toContainText('src/entry.js:3:10');
  await expect(reachability).toContainText('return isNumber(42);');
  await reachability.getByLabel('Affected export (user-declared)', { exact: true }).fill('');
  await reachability.getByRole('button', { name: 'Analyze scoped reachability' }).click();
  await expect(reachability.getByRole('status')).toContainText('UNKNOWN — insufficient static evidence');
  await expect(reachability).toContainText('No affected-function export mapping supplied.');
  await page.screenshot({ path: '/tmp/traceguard-dependency-graph.png', fullPage: true });
  await page.unroute('**/api/scans/*/vulnerabilities');
  await page.route('**/api/scans/*/vulnerabilities', route => route.fulfill({ status: 503, json: { error: 'OSV unavailable; retry later.' } }));
  await page.getByRole('button', { name: 'Check security findings' }).click();
  await expect(page.getByRole('alert')).toContainText('OSV unavailable');
  await expect(details).toContainText('Advisory status is unknown.');
  expect(errors).toEqual([]);
});
