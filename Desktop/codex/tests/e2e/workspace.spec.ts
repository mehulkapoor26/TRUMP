import { test, expect } from '@playwright/test';
import { ZipFile } from 'yazl';
import { once } from 'node:events';
import { readFile } from 'node:fs/promises';
import type { ScanResult, VulnerabilityReport } from '../../shared/src/index.js';

test('landing, saved scan navigation, charts, findings, exports and mobile layout use real scan data', async ({ page, request }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const zip = new ZipFile(); const chunks: Buffer[] = []; zip.outputStream.on('data', c => chunks.push(c)); const done = once(zip.outputStream, 'end');
  for (const name of ['package.json', 'package-lock.json', 'src/entry.js']) zip.addBuffer(await readFile(`tests/fixtures/npm-project/${name}`), name);
  zip.end(); await done;
  const created = await request.post('/api/scans', { multipart: { archive: { name: 'workspace-fixture.zip', mimeType: 'application/zip', buffer: Buffer.concat(chunks) } } });
  expect(created.status()).toBe(201); const scan = await created.json() as ScanResult;
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Know your dependencies.');
  await page.screenshot({ path: '/tmp/traceguard-landing.png', fullPage: true });
  await page.getByRole('link', { name: 'Capabilities', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Go beyond a list of dependencies.' })).toBeInViewport();
  await page.getByRole('link', { name: 'Open workspace', exact: true }).first().click();
  await expect(page.getByRole('heading', { name: 'Project scan results', exact: true })).toBeVisible();
  const nav = page.getByRole('navigation', { name: 'Workspace navigation' });
  await nav.getByRole('link', { name: 'Saved scans' }).click();
  await page.getByLabel('Search scans').fill(scan.id);
  await page.getByRole('link', { name: `Open scan ${scan.id}`, exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Active scan' })).toHaveValue(scan.id);
  await expect(page.getByText('Dependency instances', { exact: true })).toBeVisible();
  await expect(page.getByText('Unresolved declarations', { exact: true })).toBeVisible();
  await expect(page.getByText('Dependency inventory:')).toBeVisible();
  await expect(page.locator('.scan-lifecycle')).not.toContainText('Checking OSV advisories');
  await page.screenshot({ path: '/tmp/traceguard-dashboard.png', fullPage: true });
  await page.route('**/api/scans/*/vulnerabilities', route => {
    const report: VulnerabilityReport = { source: 'OSV', checkedAt: new Date().toISOString(), status: 'complete', warnings: [], checks: scan.graph!.nodes.map(n => ({ nodeId: n.id, status: n.name === 'is-number' && n.version === '6.0.0' ? 'matched' : n.isProject ? 'unknown' : 'no-known', complete: !n.isProject, advisoryIds: n.name === 'is-number' && n.version === '6.0.0' ? ['GHSA-browser-fixture'] : [] })) };
    return route.fulfill({ json: report });
  });
  await nav.getByRole('link', { name: 'Security findings' }).click();
  await page.getByRole('button', { name: 'Check security findings' }).click();
  await page.getByLabel('Filter findings by status').selectOption('matched');
  const card = page.locator('.finding-card').filter({ hasText: 'GHSA-browser-fixture' });
  await expect(card).toHaveCount(1); await expect(card).toContainText('6.0.0');
  await expect(page.getByText('Unique advisory IDs')).toBeVisible();
  await card.getByRole('link', { name: 'Run scoped function analysis' }).click();
  await expect(page.getByRole('heading', { name: 'Function paths', exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: 'Scoped function reachability' })).toBeVisible();
  await expect(page.getByRole('combobox', { name: 'Active scan' })).toHaveValue(scan.id);
  await nav.getByRole('link', { name: 'Project results', exact: true }).click();
  const download = page.waitForEvent('download'); await page.getByRole('link', { name: 'Export SBOM', exact: true }).click();
  expect((await download).suggestedFilename()).toBe(`traceguard-${scan.id}.cdx.json`);
  await page.getByRole('button', { name: 'Analysis scope and help' }).click();
  await expect(page.getByRole('dialog')).toBeVisible(); await page.keyboard.press('Escape'); await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'Open navigation', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
  await nav.getByRole('link', { name: 'Scan another project' }).click();
  await expect(page.getByRole('heading', { level: 1, name: 'Scan your project', exact: true })).toBeVisible();
  await expect(page.getByRole('combobox', { name: 'Project source', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await expect(page.locator('.sidebar')).not.toBeInViewport();
  await page.screenshot({ path: '/tmp/traceguard-mobile.png', fullPage: true });
  await page.goto('/#/');
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
